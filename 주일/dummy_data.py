# 일요일은 전원, 수요일은 일부만 출석하는 더미 출석 데이터 생성기
def build_attendance(user_rows):
    services = [
        ('2026-07-05', 'sunday'),
        ('2026-07-12', 'sunday'),
        ('2026-07-15', 'wednesday'),
        ('2026-07-19', 'sunday'),
        ('2026-07-26', 'sunday'),
        ('2026-07-29', 'wednesday'),
        ('2026-08-02', 'sunday'),
        ('2026-08-09', 'sunday'),
        ('2026-08-12', 'wednesday'),
        ('2026-08-16', 'sunday'),
        ('2026-08-23', 'sunday'),
        ('2026-08-26', 'wednesday'),
        ('2026-08-29', 'sunday'),
    ]
    att = []
    for si, (date, mode) in enumerate(services):
        for i, row in enumerate(user_rows):
            name, _, affiliation, *_ = row
            if mode == 'wednesday' and i % 3 != 0:
                continue
            minute = (si * 37 + i * 7) % 45 + 5
            att.append((name, affiliation, date, '09:%02d:00' % minute, mode))
    return att